// Writes sdk/src/abi.ts from the Foundry build output (run `forge build` in contracts/ first).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (file, name) => JSON.parse(readFileSync(join(root, 'contracts/out', file, `${name}.json`), 'utf8')).abi;
const out = '// Generated by scripts/gen-abi.mjs from contracts/out. Do not edit by hand.\n' +
  `export const perpsAbi = ${JSON.stringify(read('KumiPerps.sol', 'KumiPerps'))} as const;\n\n` +
  `export const crewAbi = ${JSON.stringify(read('KumiCrew.sol', 'KumiCrew'))} as const;\n\n` +
  `export const factoryAbi = ${JSON.stringify(read('KumiCrew.sol', 'KumiCrewFactory'))} as const;\n\n` +
  `export const usdcAbi = ${JSON.stringify(read('TestUSDC.sol', 'TestUSDC'))} as const;\n\n` +
  `export const lobbyAbi = ${JSON.stringify(read('KumiLobby.sol', 'KumiLobby'))} as const;\n\n` +
  `export const gasStationAbi = ${JSON.stringify(read('KumiGasStation.sol', 'KumiGasStation'))} as const;\n`;
writeFileSync(join(root, 'sdk/src/abi.ts'), out);
console.log('wrote sdk/src/abi.ts');

// Ava Labs' EncryptedERC and Registrar ABIs from the pinned submodule's build (FOUNDRY_PROFILE=eerc forge build).
const readE = (name) => JSON.parse(readFileSync(join(root, 'contracts/out-eerc', `${name}.sol`, `${name}.json`), 'utf8')).abi;
writeFileSync(join(root, 'sdk/src/eerc-abi.ts'),
  '// Generated by scripts/gen-abi.mjs from contracts/out-eerc (Ava Labs EncryptedERC, pinned submodule). Do not edit by hand.\n' +
  `export const encryptedErcAbi = ${JSON.stringify(readE('EncryptedERC'))} as const;\n\n` +
  `export const registrarAbi = ${JSON.stringify(readE('Registrar'))} as const;\n`);
console.log('wrote sdk/src/eerc-abi.ts');
