// Writes sdk/src/deployment.ts from deployments/fuji.json so the app and scripts share one set of addresses.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const d = JSON.parse(readFileSync(join(root, 'deployments/fuji.json'), 'utf8'));
const c = d.contracts;
const out = {
  usdc: c.usdc, perps: c.perps,
  // Ava Labs EncryptedERC (converter over tUSDC) and its Registrar: Kumi's private balance.
  eerc: c.eerc ? { encryptedERC: c.eerc.encryptedERC, registrar: c.eerc.registrar, auditor: d.accounts?.auditor ?? null, deployBlock: (d.eerc ?? []).find(t => t.label === 'deploy_EncryptedERC')?.block ?? 0 } : null, factory: c.factory, crewImplementation: c.crewImplementation, lobby: c.lobby,
  // KumiGasStation: a first sip of Fuji AVAX for brand-new wallets (v2.2), and the relayer key Kumi's API holds.
  gasStation: c.gasStation ?? null,
  // First block of the venue: where fill history (and so the caller leaderboard) starts.
  perpsDeployBlock: (d.txs ?? []).find(t => t.label === 'deploy_KumiPerps')?.block ?? 0, gasSponsor: d.accounts?.sponsor ?? null,
  lobbyChannels: d.lobbyChannels ?? {},
  // Kumi's own test accounts (keys in the operator's gitignored .env). The apps label them as test accounts.
  testAccounts: [...Object.entries(d.accounts ?? {}).filter(([n]) => n !== 'deployer').map(([, a]) => a.toLowerCase()), ...Object.values(d.phoneQaWallets ?? {}).map(a => a.toLowerCase())],
  crews: (c.crews ?? []).map(x => ({ name: x.name, address: x.address })),
  // Labels for the test accounts so the room says "mika" instead of 0x8574…3acF.
  names: Object.fromEntries([...Object.entries(d.accounts ?? {}).map(([n, a]) => [a.toLowerCase(), n]), ...Object.entries(d.phoneQaWallets ?? {}).map(([n, a]) => [a.toLowerCase(), n]), ...(c.crews ?? []).map(x => [x.address.toLowerCase(), `${x.name} vault`])]),
  deployTxs: Object.fromEntries((d.txs ?? []).filter(t => t.label.startsWith('deploy_') || t.label.startsWith('list_') || t.label === 'create_crew_night_owls'), ...(d.seedV2 ?? []).filter(t => t.label === 'deploy_KumiLobby' || t.label.startsWith('create_crew_') || t.label.startsWith('channel_')).map(t => [t.label, t.hash])),
};
writeFileSync(join(root, 'sdk/src/deployment.ts'), `// Generated by scripts/gen-deployment.mjs from deployments/fuji.json. Do not edit by hand.\nexport const DEPLOYMENT = ${JSON.stringify(out, null, 2)} as const;\n`);
console.log('wrote sdk/src/deployment.ts');
