// Writes sdk/src/deployment.ts from deployments/fuji.json so the app and scripts share one set of addresses.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const d = JSON.parse(readFileSync(join(root, 'deployments/fuji.json'), 'utf8'));
const c = d.contracts;
const out = {
  usdc: c.usdc, perps: c.perps, factory: c.factory, crewImplementation: c.crewImplementation,
  crews: (c.crews ?? []).map(x => ({ name: x.name, address: x.address })),
  // Labels for the test accounts so the room says "mika" instead of 0x8574…3acF.
  names: Object.fromEntries(Object.entries(d.accounts ?? {}).map(([n, a]) => [a.toLowerCase(), n])),
  deployTxs: Object.fromEntries((d.txs ?? []).filter(t => t.label.startsWith('deploy_') || t.label.startsWith('list_') || t.label === 'create_crew_night_owls').map(t => [t.label, t.hash])),
};
writeFileSync(join(root, 'sdk/src/deployment.ts'), `// Generated by scripts/gen-deployment.mjs from deployments/fuji.json. Do not edit by hand.\nexport const DEPLOYMENT = ${JSON.stringify(out, null, 2)} as const;\n`);
console.log('wrote sdk/src/deployment.ts');
